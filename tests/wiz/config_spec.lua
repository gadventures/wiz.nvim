local config = require("wiz.config")

describe("wiz.config", function()
  before_each(function()
    config.setup({})
  end)

  it("has defaults", function()
    local c = config.get()
    assert.equals("wizcli", c.wizcli_path)
    assert.is_false(c.scan_on_save)
    assert.is_true(c.scan_on_open)
    assert.equals("LOW", c.min_severity)
    assert.equals("<leader>z", c.keymaps.prefix)
    assert.same({ "iac", "secret", "vuln" }, c.scan_types)
  end)

  it("deep-merges user opts", function()
    config.setup({ min_severity = "HIGH", env = { client_id = "MY_ID" } })
    local c = config.get()
    assert.equals("HIGH", c.min_severity)
    assert.equals("MY_ID", c.env.client_id)
    assert.equals("WIZ_CLIENT_SECRET", c.env.client_secret)
  end)

  it("replaces list options instead of merging them by index", function()
    config.setup({ scan_types = { "iac" }, wizcli_args = { "--policy", "X" } })
    assert.same({ "iac" }, config.get().scan_types)
    assert.same({ "--policy", "X" }, config.get().wizcli_args)
  end)

  it("normalizes severity case", function()
    config.setup({ min_severity = "medium" })
    assert.equals("MEDIUM", config.get().min_severity)
  end)

  it("allows disabling keymaps", function()
    config.setup({ keymaps = false })
    assert.is_false(config.get().keymaps)
  end)

  it("rejects bad values", function()
    assert.has_error(function()
      config.setup({ min_severity = "SPICY" })
    end)
    assert.has_error(function()
      config.setup({ picker = "nope" })
    end)
    assert.has_error(function()
      config.setup({ timeout_ms = -1 })
    end)
    assert.has_error(function()
      config.setup({ scan_types = { "iac", "sast" } })
    end)
  end)

  it("does not mutate defaults", function()
    config.setup({ env = { client_id = "OTHER" } })
    assert.equals("WIZ_CLIENT_ID", config.defaults.env.client_id)
  end)

  it("ranks severities", function()
    assert.is_true(config.rank("CRITICAL") > config.rank("HIGH"))
    assert.is_true(config.rank("high") > config.rank("MEDIUM"))
    assert.equals(config.rank("INFO"), config.rank("unknown"))
  end)
end)
